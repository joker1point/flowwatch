"""开机自启开关（Windows 注册表 Run 键，HKCU —— 无需管理员）。

为什么选这个方案：计划任务更强但要 schtasks（可能触发 UAC），启动文件夹要造 .lnk；
Run 键一行写入、一行删除，用户级生效，是最轻的可逆做法。

两条刻意的诚实：
  · 非 Windows 平台直接回 "不支持"，不假装成功；
  · 写进去的命令 = 「当前这条启动命令」（打包成 exe 时就是 exe 本身 + 当前参数）——
    即"把现在这条命令记下来"，而不是猜一个推荐命令（设备、端口、保留天数都以现状为准）。

**resident.cmd 启动器（2026-10-15 新增）**：Run 键不再直接指向 python——
直接指向时进程的 stdout/stderr 无处可去（Run 键启动没有 console），崩溃即"静默死亡、
死因不可考"（E-24，10-15 诊断实录：采集进程 15:18~17:01 间死亡，无转储无日志）。
改为指向同目录的 resident.cmd：由它 `cd` 到项目目录并把输出重定向进
`_run/resident.log`。本模块负责生成/更新该文件，保证「开关自启」与「启动器内容」同源。
"""

import logging
import sys
from pathlib import Path
from typing import Any

logger = logging.getLogger("flowwatch.autostart")

VALUE_NAME = "flowwatch"
RUN_KEY = r"Software\Microsoft\Windows\CurrentVersion\Run"
RESIDENT_CMD = Path(__file__).with_name("resident.cmd")
RESIDENT_LOG = "_run/resident.log"


def bare_command() -> str:
    """不带包装的「当前这条启动命令」（python/exe + 原样参数）。"""
    if getattr(sys, "frozen", False):
        # 打包成 exe：解释器就是 exe 本身，参数原样带走（run.py 的单端口参数）
        parts = [f'"{sys.executable}"']
    else:
        parts = [f'"{sys.executable}"', f'"{Path(__file__).with_name("server.py")}"']
    for arg in sys.argv[1:]:
        parts.append(f'"{arg}"' if " " in arg else arg)
    return " ".join(parts)


def ensure_resident_cmd() -> Path:
    """生成/更新 resident.cmd（内容 = 当前启动命令 + 日志重定向）。返回路径。

    .cmd 必须 CRLF（E-20：LF 版本机侥幸能跑、交付必炸）；内容保持纯 ASCII。
    """
    lines = [
        "@echo off",
        "rem flowwatch resident launcher (generated by autostart.py)",
        "rem Run-key -> this file -> python server.py with output to _run/resident.log",
        "cd /d %~dp0",
        "if not exist _run mkdir _run",
        f"{bare_command()} >> {RESIDENT_LOG} 2>&1",
        "",
    ]
    RESIDENT_CMD.write_bytes(("\r\n".join(lines)).encode("ascii"))
    logger.info("已更新 resident 启动器: %s", RESIDENT_CMD)
    return RESIDENT_CMD


def current_command() -> str:
    """自启命令：源码运行 → cmd 包装的 resident.cmd（日志落盘，E-24）；
    exe 运行 → exe 本身 + 参数原样（PyInstaller 形态没有 server.py 可包装）。"""
    if getattr(sys, "frozen", False):
        return bare_command()
    if RESIDENT_CMD.exists():
        return f'cmd /c "{RESIDENT_CMD}"'
    return bare_command()


def _read_value() -> str | None:
    import winreg

    try:
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, RUN_KEY) as key:
            value, _ = winreg.QueryValueEx(key, VALUE_NAME)
            return str(value)
    except OSError:
        return None


def status() -> dict[str, Any]:
    if sys.platform != "win32":
        return {"supported": False, "enabled": False, "command": "", "detail": "仅 Windows 支持"}
    saved = _read_value()
    return {
        "supported": True,
        "enabled": saved is not None,
        "command": saved or current_command(),   # 未启用时给出"启用后会写入的命令"
        "detail": "HKCU Run 键（无需管理员，随时可关）→ resident.cmd 启动器（输出落 _run/resident.log）",
    }


def set_enabled(enabled: bool) -> dict[str, Any]:
    if sys.platform != "win32":
        return {"supported": False, "enabled": False, "command": "", "detail": "仅 Windows 支持"}
    import winreg

    if enabled:
        # 先保证启动器与「当前这条命令」同源，再写键——否则键指向的可能是旧参数/旧解释器
        if not getattr(sys, "frozen", False):
            ensure_resident_cmd()
    command = current_command()
    with winreg.CreateKeyEx(winreg.HKEY_CURRENT_USER, RUN_KEY, 0, winreg.KEY_SET_VALUE) as key:
        if enabled:
            winreg.SetValueEx(key, VALUE_NAME, 0, winreg.REG_SZ, command)
            logger.info("已开启开机自启: %s", command)
        else:
            try:
                winreg.DeleteValue(key, VALUE_NAME)
                logger.info("已关闭开机自启")
            except FileNotFoundError:
                pass
    result = status()
    if enabled:
        result["command"] = command
    return result
